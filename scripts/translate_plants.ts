function main() {
  const jsonPath = resolve(process.cwd(), 'src/data/herbiq-plants.json');
  const rawPlants: Plant[] = JSON.parse(readFileSync(jsonPath, 'utf8'));

  const updatedPlants = rawPlants.map((plant) => {
    const arDraft = ARABIC_PLANT_DRAFTS[plant.id];
    const mlDraft: PlantTranslation = {
      ...(plant.translations?.ml || {}),
      name: plant.malayalamName,
    };
    return {
      ...plant,
      translations: {
        ...(plant.translations || {}),
        ...(arDraft ? { ar: arDraft } : {}),
        ml: mlDraft,
      },
    };
  });

  writeFileSync(jsonPath, JSON.stringify(updatedPlants, null, 2) + '\n', 'utf8');

  const draftReport = {
    _meta: {
      status: 'AI_DRAFT_REQUIRES_ADMIN_REVIEW',
      generatedAt: new Date().toISOString(),
      plantCount: Object.keys(ARABIC_PLANT_DRAFTS).length,
      note: 'Review in HerbiQ Admin before saving to production Supabase database. No new medical claims added.',
    },
    drafts: ARABIC_PLANT_DRAFTS,
  };

  const outDraftsPath = resolve(process.cwd(), 'supabase/arabic_drafts_28_plants.json');
  writeFileSync(outDraftsPath, JSON.stringify(draftReport, null, 2) + '\n', 'utf8');

  console.log(`Updated ${updatedPlants.length} plants in src/data/herbiq-plants.json and wrote 28 Arabic drafts to supabase/arabic_drafts_28_plants.json.`);
}

main();
